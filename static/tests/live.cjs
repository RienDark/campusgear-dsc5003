'use strict';
// Run only against an isolated, freshly seeded local test DB (this creates bookings).
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { Document, descendants } = require('./dom.cjs');
const { createWorkspace, apiRequest } = require('../app.js');
const base = process.argv[2];
if (!/^http:\/\/127\.0\.0\.1:\d+$/.test(base || '')) throw new Error('Pass isolated local server URL');
const doc = new Document(fs.readFileSync(path.join(__dirname, '..', 'index.html'), 'utf8'));
const controller = createWorkspace(doc, (url, options) => apiRequest(base + url, options));
const $ = id => doc.getElementById(id);
const buttons = id => descendants($(id)).filter(el => el.tagName === 'BUTTON');
(async () => {
  await controller.start();
  assert.equal($('connection-status').textContent, 'Database connected');
  const dashboard = await apiRequest(base + '/api/dashboard');
  assert.equal($('metric-equipment').textContent, String(dashboard.equipment_count));
  await buttons('equipment-body').find(el => !el.disabled).emit('click');
  $('booking-purpose').value = 'Frontend isolated API verification';
  await $('booking-form').emit('submit');
  assert.match($('booking-feedback').textContent, /confirmed/);
  await $('booking-form').emit('submit');
  assert.match($('booking-feedback').textContent, /overlap|conflict/i);
  await $('nav-reservations').emit('click');
  await buttons('reservations-body').find(el => el.textContent === 'Cancel').emit('click');
  assert.match($('notice').textContent, /cancelled/);
  await $('nav-equipment').emit('click');
  await $('booking-form').emit('submit');
  assert.match($('booking-feedback').textContent, /confirmed/);
  await $('nav-reservations').emit('click');
  await buttons('reservations-body').find(el => el.textContent === 'Check out').emit('click');
  assert.match($('notice').textContent, /checked out/);
  assert.equal($('metric-loans').textContent, '1');
  await buttons('reservations-body').find(el => el.textContent === 'Return').emit('click');
  assert.match($('notice').textContent, /returned/);
  assert.equal($('metric-loans').textContent, '0');
  await $('nav-analytics').emit('click');
  assert.match($('category-usage').textContent, /Cameras2/);
  await $('nav-database').emit('click');
  assert.match($('schema-objects').textContent, /CREATE TABLE/);
  assert.match($('audit-body').textContent, /returned/);
  const stored = await apiRequest(base + '/api/reservations');
  assert.deepEqual(stored.items.map(item => item.status).sort(), ['cancelled', 'returned']);
  console.log('PASS live API + actual frontend controller: load, select, create, conflict, cancel, rebook, checkout, return, summary readback, analytics, SQL and audit.');
})().catch(error => { console.error(error); process.exitCode = 1; });
